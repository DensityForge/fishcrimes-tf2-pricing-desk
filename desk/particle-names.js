export function foldParticleName(name) {
  let s = String(name || '').toLowerCase();
  s = s.replace(/^[\s\u00a0]*(?:non-?craftable|uncraftable)\s+/i, '');
  // Quality words only — keep Haunted (effect), not quality 13.
  for (;;) {
    const next = s.replace(/^[\s\u00a0]*(?:strange|unusual|collector'?s|genuine|vintage)\s+/i, '');
    if (next === s) break;
    s = next;
  }
  s = s.replace(/^[\s\u00a0]*the\s+/i, '');
  return s.replace(/[-']/g, ' ').replace(/[\s\u00a0]+/g, ' ').trim();
}

const FOLDED = (() => {
  const out = Object.create(null);
  for (const [name, id] of Object.entries(PARTICLE_BY_NAME)) {
    const key = foldParticleName(name);
    if (key && out[key] == null) out[key] = id;
  }
  return Object.freeze(out);
})();

const PREFIXES = Object.keys(FOLDED).sort((a, b) => b.length - a.length || a.localeCompare(b));

/** Longest known effect prefix on a listing name. Null if none. */
export function peelParticleFromName(name) {
  const folded = foldParticleName(name);
  if (!folded) return null;
  for (const pref of PREFIXES) {
    if (folded === pref) return FOLDED[pref];
    if (folded.startsWith(`${pref} `)) return FOLDED[pref];
  }
  return null;
}

